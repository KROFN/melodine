_lang = "ru"


def set_language(lang: str) -> None:
    """Switch the active language (ru | en). Unknown values are ignored."""
    global _lang
    normalized = (lang or "").strip().lower()
    if normalized in _strings:
        _lang = normalized


def get_language() -> str:
    return _lang


def available_languages() -> list[str]:
    return list(_strings)


def t(key: str, **kwargs: object) -> str:
    """Translate ``key`` with optional ``str.format`` placeholders."""
    s = _strings.get(_lang, _strings["en"]).get(key)
    if s is None:
        s = _strings["en"].get(key, key)
    if kwargs:
        try:
            return s.format(**kwargs)  # type: ignore[arg-type]
        except (KeyError, IndexError, ValueError):
            return s
    return s


